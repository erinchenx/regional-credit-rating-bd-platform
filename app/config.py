#【Intermediate 层】
# ──────────────────────────────────────────────
# 
# 由于 Staging 层已经把数据“洗干净”了，Intermediate 层最怕两件事：

# 膨胀度检查：因为关联键（城市）有重复，导致 Join 后行数无故变多（1 条债变 2 条）
#           这个问题在staging层已解决，这里设置兜底检查，这里也可以删掉。

# 覆盖率检查：①由于名称不一致（如“成都市” vs “成都”），导致债券关联不到任何财力数据；
#           ②由于存在孤儿记录：债券表里有“喀什地区”，但财力库里漏掉了这个地区。Staging 不会报错（因为喀什在财力表里不重复），但 Join 之后，喀什的债券就会丢失所有财力指标。


# 膨胀度阈值：
# Hard Check，使用Raise ValueError。
# Join 后的行数 / 原行数。理论上应为 1.0。
# 考虑到可能存在的极少数异常，设为 1.01（即允许 1% 的膨胀，超规则报错）
INT_JOIN_EXPANSION_THRESHOLD = 1.01

# 覆盖率预警阈值：
# Soft Warning，使用logger.warning(msg) + st.warning()
# 如果全省债项能匹配到财力的数据低于此阈值，说明财力文件可能不全或名称不匹配
INT_JOIN_MATCH_RATE_THRESHOLD = 0.80




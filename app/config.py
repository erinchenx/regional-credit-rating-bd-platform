# BOND_VALUE_LOW_NULL
#   允许有极少数的空值。超过允许的比例范围 → 立即报错，阻断流程。
#   Hard Check，使用Raise ValueError
#   原因：发行人名称、省份、城市是所有下游 JOIN/去重/切片的 key，
#
# BOND_VALUE_WARN_NULL
#   允许部分空值、但空值率超过阈值时发出警告的字段。  
#   Soft Warning，使用st.warning
#   原因：财务数据未披露是正常业务现象，但如果某列 80% 以上都空，
#         很可能是导出时漏选了字段，值得提醒,但不中断流程。

